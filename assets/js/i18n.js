/* ══════════════════════════════════════════════════════════════════════════
   MOTOR
   Guarda a escolha no navegador, adivinha o idioma na primeira visita e
   reaplica a página inteira sem recarregar. Quem tem texto montado por
   JavaScript (mapa, preços, filtros) escuta o evento "tdm:idioma".
   ══════════════════════════════════════════════════════════════════════════ */
(function () {
  "use strict";

  var DIC = window.TDM_I18N;
  var CHAVE = "tdm.idioma";
  var HTML_LANG = { pt: "pt-BR", en: "en", es: "es" };

  function suportado(l) { return l && DIC[l] ? l : null; }

  function detectar() {
    try {
      var salvo = suportado(localStorage.getItem(CHAVE));
      if (salvo) return salvo;
    } catch (e) { /* navegação privada: segue sem guardar */ }
    var lista = navigator.languages || [navigator.language || "pt"];
    for (var i = 0; i < lista.length; i++) {
      var raiz = String(lista[i]).toLowerCase().split("-")[0];
      if (raiz === "pt") return "pt";
      if (raiz === "es") return "es";
      if (raiz === "en") return "en";
    }
    return "pt";
  }

  var API = {
    atual: "pt",
    t: function (chave, vars) {
      var dic = DIC[API.atual] || DIC.pt;
      var txt = dic[chave] != null ? dic[chave] : (DIC.pt[chave] != null ? DIC.pt[chave] : "");
      if (vars) Object.keys(vars).forEach(function (k) { txt = txt.replace("{" + k + "}", vars[k]); });
      return txt;
    },
    usar: function (lang, guardar) {
      lang = suportado(lang) || "pt";
      API.atual = lang;
      var dic = DIC[lang];

      document.documentElement.lang = HTML_LANG[lang] || lang;

      var ehGaleria = /galeria\.html/.test(location.pathname);
      document.title = API.t(ehGaleria ? "meta.title.gal" : "meta.title");
      var desc = document.querySelector('meta[name="description"]');
      if (desc) desc.setAttribute("content", API.t("meta.desc"));

      Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (el) {
        var v = dic[el.getAttribute("data-i18n")];
        if (v != null) el.innerHTML = v;
      });
      Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-attr]"), function (el) {
        el.getAttribute("data-i18n-attr").split(";").forEach(function (par) {
          var p = par.split(":");
          var v = dic[p[1]];
          if (p[0] && v != null) el.setAttribute(p[0].trim(), v);
        });
      });

      Array.prototype.forEach.call(document.querySelectorAll("[data-lang-atual]"), function (el) {
        el.textContent = lang.toUpperCase();
      });
      Array.prototype.forEach.call(document.querySelectorAll("[data-lang-op]"), function (b) {
        b.setAttribute("aria-selected", b.getAttribute("data-lang-op") === lang);
      });

      if (guardar) { try { localStorage.setItem(CHAVE, lang); } catch (e) {} }
      document.dispatchEvent(new CustomEvent("tdm:idioma", { detail: { lang: lang } }));
    }
  };

  function ligaSeletor() {
    Array.prototype.forEach.call(document.querySelectorAll("[data-lang]"), function (caixa) {
      var botao = caixa.querySelector("[data-lang-btn]");
      var lista = caixa.querySelector("[data-lang-lista]");
      if (!botao || !lista) return;

      function fechar() { lista.hidden = true; botao.setAttribute("aria-expanded", "false"); }
      botao.addEventListener("click", function (e) {
        e.stopPropagation();
        var abrir = lista.hidden;
        // fecha qualquer outro seletor aberto na página
        Array.prototype.forEach.call(document.querySelectorAll("[data-lang-lista]"), function (o) { o.hidden = true; });
        Array.prototype.forEach.call(document.querySelectorAll("[data-lang-btn]"), function (o) { o.setAttribute("aria-expanded", "false"); });
        lista.hidden = !abrir;
        botao.setAttribute("aria-expanded", String(abrir));
      });
      Array.prototype.forEach.call(lista.querySelectorAll("[data-lang-op]"), function (op) {
        op.addEventListener("click", function () { API.usar(op.getAttribute("data-lang-op"), true); fechar(); });
      });
      document.addEventListener("click", function (e) { if (!caixa.contains(e.target)) fechar(); });
      document.addEventListener("keydown", function (e) { if (e.key === "Escape") fechar(); });
    });
  }

  function iniciar() { API.usar(detectar(), false); ligaSeletor(); }
  window.TDM_LANG = API;
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", iniciar);
  else iniciar();
})();
